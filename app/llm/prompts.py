"""提示词模板。

设计要点：
- RAG 问答强制「只依据资料 + 不知道就说不知道」：学校通知类信息答错后果严重，
  宁可说没找到也不能编造金额、日期、地点。
- 每个片段带编号，要求模型引用编号，前端据此回溯原文位置。
"""

def build_user_profile(user: dict | None) -> str:
    """把 config.yaml 的 user 段渲染成系统提示词里的身份卡。

    让 AI 知道聊天记录里哪个名字是用户本人，回答「安排/待办」类问题时
    能主动关联到用户本人的职责与前置准备。未配置时返回空字符串。
    """
    if not user:
        return ""
    name = (user.get("name") or "").strip()
    nickname = (user.get("nickname") or "").strip()
    qq = int(user.get("qq") or 0)
    roles = [str(r).strip() for r in (user.get("roles") or []) if str(r).strip()]
    context = (user.get("context") or "").strip()
    if not (name or nickname or qq or context):
        return ""

    aliases = []
    if name:
        aliases.append(f"姓名「{name}」")
    if nickname:
        aliases.append(f"QQ 昵称「{nickname}」")
    if qq:
        aliases.append(f"QQ 号 {qq}")
    profile = "【用户本人身份】\n与你对话的用户就是" + "、".join(aliases) + "。"
    profile += ("聊天记录中出现以上任何一个名字/账号，指的就是用户本人；"
                "别人 @ 他、给他指派任务、提到他的职责时，都与用户直接相关。")
    if roles:
        profile += "\n用户当前担任：" + "、".join(roles) + "。"
    if context:
        profile += "\n【用户自己的场景】\n" + context
    return profile


def build_group_list(groups: list[dict] | None) -> str:
    """把数据库里的会话（群 + 好友私聊）渲染成「群号 ↔ 群名」对照表。

    search_chat 的 group_id 参数是数字，模型只有看到这张表才能把
    「班级群」「项目组」这类说法转成群号或会话。没有会话时返回空字符串。
    """
    if not groups:
        return ""
    lines: list[str] = []
    for g in groups[:60]:
        gid = int(g.get("group_id") or 0)
        if not gid:
            continue
        name = (g.get("name") or "").strip() or f"会话 {gid}"
        n = int(g.get("msg_count") or 0)
        kind = "好友" if gid < 0 else "群"
        lines.append(f"- {gid}（{kind}）{name}" + (f" · {n} 条" if n else ""))
    if not lines:
        return ""
    return ("【可用的会话清单】search_chat 的 group_id 参数用下面的数字；"
            "用户说群名时按名称匹配：\n" + "\n".join(lines))


