def build_context(chunks: list[dict], max_chars: int) -> tuple[str, list[dict]]:
    """把检索到的片段拼成上下文。返回 (文本, 实际使用的片段)。

    超长时从尾部丢弃低分片段（片段已按相关度降序）。
    """
    parts: list[str] = []
    used: list[dict] = []
    total = 0
    for i, c in enumerate(chunks, 1):
        tag = f"[{i}] 来源：{c['source']}"
        if c.get("day"):
            tag += f" · {c['day']}"
        body = c["text"].strip()
        block = f"{tag}\n{body}"
        if total + len(block) > max_chars and used:
            break  # 至少保留一个片段
        parts.append(block)
        used.append({**c, "ref": i})
        total += len(block)
    return "\n\n---\n\n".join(parts), used


