"""判断用户这句话是否需要查知识库。

为什么需要：早期版本对每句话都强制检索并套「没找到就说没找到」，
导致用户说「你好」时 AI 也去翻知识库然后报告"没找到"——既浪费 API 调用，
体验也很糟。

判断策略（按成本从低到高，命中即返回）：
    1. 规则快速判定：寒暄、闲聊、通用知识、明显与资料无关
    2. 语料查询特征：含疑问词/时间词/事务关键词 → 需要检索
    3. 兜底：短句（<=8 字）且无查询特征 → 当作闲聊

说明：这是启发式规则，不是语义理解。二期接 Function Calling 后，
可改由模型自己决定是否调用检索工具，那时本模块可降级为「预过滤器」
（只在明显是寒暄时跳过，其余交给模型判断）。
"""
from __future__ import annotations

import re

# 明确的寒暄/闲聊（去掉标点后整句匹配）
_SMALLTALK = {
    "你好", "您好", "hi", "hello", "hey", "嗨", "哈喽", "早上好", "中午好",
    "下午好", "晚上好", "在吗", "在么", "你是谁", "你叫什么", "你是机器人吗",
    "谢谢", "感谢", "thanks", "thank you", "好的", "嗯", "哦", "明白",
    "再见", "拜拜", "bye", "辛苦了", "没问题", "收到", "好的谢谢",
    "你能做什么", "你能干嘛", "你会什么", "有什么功能", "帮助", "help",
    "测试", "测试一下", "哈哈哈", "哈哈", "呵呵", "无语", "牛", "厉害",
}

# 通用知识 / 与班级事务无关（这类问题不该去翻聊天记录）
_GENERAL = [
    r"^(今天|明天|昨天)天气", r"天气怎么样", r"^(现在|今天)几点",
    r"^(帮我)?(写|生成|翻译|润色)", r"^(计算|算一下)",
    r"^(什么是|什么是|解释一下).{0,6}$",
]

# 需要查资料的特征
_QUERY_HINT = [
    # 疑问词
    r"什么|怎么|如何|多少|哪些|哪天|何时|谁|为什么|是不是|有没有|可以吗",
    # 时间指向
    r"今天|昨天|明天|本周|这周|上周|本月|这月|最近|最近一次|上次|之前|以前",
    r"开学|期末|期中|暑假|寒假|学期|报到|注册|放假",
    # 群事务（校园与工作场景都覆盖）
    r"项目|需求|排期|进度|值班|排班|交接|报销|预算|合同|发票|客户|供应商|"
    r"招聘|面试|培训|上线|发布|评审|验收|交付|设备|物料|例会|周会|纪要"
    r"通知|安排|会议|班会|活动|报名|截止|提交|交表|作业|考试|成绩|学分",
    r"学费|住宿|宿舍|食堂|体检|疫苗|档案|户籍|奖学|助学金|贷款|差旅|保险",
    r"老师|辅导员|班主任|同学|班级|群|群里|家长",
    r"文件|文档|表格|名单|学号|账号|激活|登录|密码",
    r"总结|归纳|整理|汇总|统计|列一下|帮我找|查一下|搜一下|找一下",
]

_GREETING_RE = re.compile(r"[\s，。！？、,.!?~～]+")
_GENERAL_RE = [re.compile(p) for p in _GENERAL]
_QUERY_RE = [re.compile(p) for p in _QUERY_HINT]


def needs_search(text: str) -> bool:
    """判断这句话是否需要检索知识库。"""
    t = (text or "").strip()
    if not t:
        return False

    # 1. 纯寒暄（去掉标点空白后整句匹配）
    bare = _GREETING_RE.sub("", t).lower()
    if bare in _SMALLTALK:
        return False

    # 2. 通用知识类问题
    for pat in _GENERAL_RE:
        if pat.search(t):
            return False

    # 3. 有明确查询特征 → 需要检索
    for pat in _QUERY_RE:
        if pat.search(t):
            return True

    # 4. 兜底：很短且不含查询特征 → 当作闲聊（如「在吗」「嗯嗯」）
    if len(t) <= 6:
        return False

    # 5. 较长但没有明显特征：默认检索（宁可多查一次，也别漏掉该查的）
    return True
